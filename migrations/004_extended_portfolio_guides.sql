A key principle for high-quality portfolio reflections.

## What Is It?

Every reflection should link to **at least three competencies** from the GP curriculum. This demonstrates:

- **Holistic thinking** - seeing the whole patient
- **Skill integration** - how competencies work together
- **Higher-level reflection** - moving beyond description

## The 13 Capabilities

1. Fitness to practise
2. Maintaining an ethical approach
3. Communication and consultation skills
4. Data gathering and interpretation
5. Clinical examination and procedural skills
6. Making decisions
7. Clinical management
8. Managing medical complexity
9. Working with colleagues and in teams
10. Maintaining performance, learning and teaching
11. Organisation, management and leadership
12. Practising holistically
13. Community orientation

## Example

**Case:** Managing a 45-year-old man with chest pain

**Three Competency Links:**

1. **Data gathering and interpretation**
   - Systematic history taking for chest pain
   - Appropriate use of ECG interpretation

2. **Making decisions**
   - Differential diagnosis (cardiac vs non-cardiac)
   - Knowing when to refer urgently

3. **Communication and consultation skills**
   - Explaining risk clearly
   - Managing patient anxiety
   - Shared decision-making about investigation

## Why Three Links Works

- Shows you understand the complexity of GP practice
- Demonstrates integrated thinking
- Moves you from descriptive to analytical reflection
- Impresses at ARCP!

## Common Mistake

Forcing inappropriate links. Don''t add competencies that aren''t genuinely relevant. Three meaningful links beat five superficial ones.', 11, false, true),

