Everything you need to know about the Annual Review of Competence Progression.

## What is ARCP?

The ARCP is an annual review that assesses whether you''re progressing satisfactorily in your training. It''s not an exam - it''s a review of your portfolio and progress.

## ARCP Outcomes

- **Outcome 1:** Satisfactory progress - continue training
- **Outcome 2:** Development of specific competencies required
- **Outcome 3:** Inadequate progress - additional training time needed
- **Outcome 4:** Released from training
- **Outcome 5:** Incomplete evidence - review at later date
- **Outcome 6:** Gained CCT/CEGPR (ST3 completion)

## What They''re Looking For

### Evidence of:
- Sufficient clinical experience
- Meeting curriculum competencies
- Passing required assessments (AKT/RCA/SCA)
- Appropriate WPBAs
- Quality reflections
- ES/CS reports
- Out of hours experience

### Quality over Quantity
- Well-written reflections > many poor ones
- Meaningful WPBA feedback > tick-box exercises
- Evidence of learning from experiences

## Timeline

- **Ongoing:** Regular WPBAs, reflections, log entries
- **3 months before:** Review portfolio gaps
- **1 month before:** ES meeting and report
- **2 weeks before:** Final portfolio check
- **ARCP day:** Panel reviews your portfolio

## Common Issues

1. **Insufficient reflections** - aim for 3 per month
2. **Missing WPBA coverage** - varied cases and assessors
3. **No curriculum mapping** - link entries to capabilities
4. **Late ES report** - book meeting early

## Top Tips

1. Don''t cram at the end - regular portfolio maintenance
2. Address feedback from previous ARCPs
3. Quality of entries matters more than quantity
4. Keep your ES informed of any concerns
5. If struggling, ask for support early', 20, true, true),

