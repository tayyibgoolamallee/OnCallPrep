('st1', 'reflection', 'Gibbs'' Reflective Cycle Explained', '# Gibbs'' Reflective Cycle

The most widely used reflection framework in healthcare education.

## The Six Stages

### 1. Description
**What happened?**
- Keep it brief and factual
- Set the scene without analysis
- Include key patient demographics, presenting complaint, your actions

### 2. Feelings
**What were you thinking and feeling?**
- Be honest about emotions
- Include uncertainty, anxiety, confidence
- This shows self-awareness

### 3. Evaluation
**What was good and bad about the experience?**
- Consider multiple perspectives
- Your perspective, the patient''s, colleagues''
- Be balanced - not all negative or positive

### 4. Analysis
**What sense can you make of the situation?**
- Link to evidence, guidelines, theory
- This is the crucial step that elevates your reflection
- Why did things happen as they did?

### 5. Conclusion
**What else could you have done?**
- Be specific about alternatives
- Consider what others might have done differently
- What have you learned?

### 6. Action Plan
**What will you do differently next time?**
- Make it concrete and achievable
- What specific learning needs arise?
- How will you follow up?

## Example Using Gibbs

**Situation:** Managing an angry patient demanding antibiotics for a viral URTI

**Description:** 45-year-old man presented with 3-day cold symptoms. Became visibly frustrated when I explained antibiotics weren''t appropriate.

**Feelings:** I felt defensive initially, then anxious about the confrontation. I was confident in my clinical decision but uncomfortable managing his anger.

**Evaluation:** Good - I stayed calm and didn''t prescribe inappropriately. Less good - I could have explored his concerns earlier.

**Analysis:** Research shows many patients attend with expectations of treatment. The ICE model (Ideas, Concerns, Expectations) could have helped me understand his perspective earlier.

**Conclusion:** I should have asked about his concerns earlier. His wife was unwell and he was worried about passing infection to her.

**Action Plan:** In future, I will use ICE early in consultations where there''s potential conflict. I will read about managing patient expectations and discuss difficult consultations with my supervisor.', 10, false, true),

